#!/usr/bin/env python3
"""Generate source/Cmf.h from the CIE 1931 2-degree colour-matching functions.

    tools/cmf_header.py           write source/Cmf.h
    tools/cmf_header.py --check   exit 1 unless source/Cmf.h is what this would write

The input is CVRL's ciexyz31_1.csv (http://cvrl.ioo.ucl.ac.uk/, "CIE 1931 2-deg,
XYZ CMFs", 1 nm, 360-830 nm), copied from filament's tools/data. Its sha256 is
checked first, so a different file can never quietly become the plugin's colour.

The header is the CSV's numbers, as written in the CSV (the strings, not a
re-rounding), so the plugin sums exactly the published table. The harness
does NOT include this header: it reads the CSV itself at run time.
"""
import hashlib
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
CSV = os.path.join(HERE, "data", "ciexyz31_1.csv")
OUT = os.path.join(HERE, "..", "source", "Cmf.h")
SHA256 = "ccbe601d7abf2227b46007ab29742f1f6bcb8621a6413283fb5ade7626a662c5"


def build():
    data = open(CSV, "rb").read()
    digest = hashlib.sha256(data).hexdigest()
    if digest != SHA256:
        sys.exit("ciexyz31_1.csv has sha256 %s, not %s" % (digest, SHA256))
    rows = []
    for line in data.decode("ascii").splitlines():
        parts = [p.strip() for p in line.split(",")]
        if len(parts) != 4:
            continue
        rows.append(parts)
    first, last = int(rows[0][0]), int(rows[-1][0])
    if [int(r[0]) for r in rows] != list(range(first, last + 1)):
        sys.exit("the CSV is not one row per nanometre")
    out = []
    out.append("#pragma once")
    out.append("")
    out.append("// GENERATED by tools/cmf_header.py from tools/data/ciexyz31_1.csv")
    out.append("// (CVRL, CIE 1931 2-degree XYZ CMFs, 1 nm; sha256 %s)." % SHA256)
    out.append("// Do not edit: re-run the script. tools/cmf_header.py --check proves it current.")
    out.append("")
    out.append("namespace carousel::cmf")
    out.append("{")
    out.append("inline constexpr int kFirstNm = %d;" % first)
    out.append("inline constexpr int kCount   = %d;" % len(rows))
    out.append("/// x-bar, y-bar, z-bar at kFirstNm + i nanometres.")
    out.append("inline constexpr double kXyz[ kCount ][ 3 ] = {")
    for r in rows:
        out.append("\t{ %s, %s, %s }, // %s nm" % (r[1], r[2], r[3], r[0]))
    out.append("};")
    out.append("} // namespace carousel::cmf")
    out.append("")
    return "\n".join(out)


def main():
    text = build()
    if "--check" in sys.argv[1:]:
        try:
            current = open(OUT).read()
        except OSError:
            current = ""
        if current != text:
            print("source/Cmf.h is not what tools/cmf_header.py writes: re-run it")
            return 1
        print("source/Cmf.h is current (%d rows)" % text.count(" nm\n"))
        return 0
    with open(OUT, "w") as f:
        f.write(text)
    print("wrote source/Cmf.h")
    return 0


if __name__ == "__main__":
    sys.exit(main())
